void play_note(uint8_t num,uint16_t time)
{
	//  (ARR = 1MHz /  - 1)
	uint16_t arr = (1000000/note_freq[num]) - 1;
  __HAL_TIM_SET_AUTORELOAD(&htim3, arr);  
	
	//  (volume: 0-5050-100)
	uint16_t pulse = (arr * 50) / 100;
	__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, pulse); 	
	HAL_TIM_PWM_Start(&htim3,TIM_CHANNEL_3);  //33PWM	
 
	HAL_Delay(time);
	HAL_TIM_PWM_Stop(&htim3,TIM_CHANNEL_3);  //33PWM
}
